export const DICTS: Record<Locale, Dict> = { ko, en, ja };

export function isLocale(v: unknown): v is Locale {
  return v === 'ko' || v === 'en' || v === 'ja';
}

// 기기 언어 코드('en-US', 'ja', 'ko-KR'…) → 우리가 가진 언어. 모르면 한국어.
export function localeFromTag(tag: string | null | undefined): Locale {
  const code = (tag ?? '').toLowerCase().split(/[-_]/)[0];
  return isLocale(code) ? code : 'ko';
}

export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const raw = DICTS[locale][key] ?? DICTS.ko[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}
